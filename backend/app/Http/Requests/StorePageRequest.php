<?php

namespace App\Http\Requests;

use App\Support\Blocks\BlockDefinitions;
use App\Support\Blocks\FieldLabels;
use Illuminate\Foundation\Http\FormRequest;
use Illuminate\Validation\Rule;

class StorePageRequest extends FormRequest
{
    /** Slugs that would collide with frontend or infrastructure routes. */
    public const RESERVED_SLUGS = ['admin', 'api', 'login', 'logout', 'preview', 'storage'];

    public function authorize(): bool
    {
        // Authorisation is enforced by PagePolicy via the controller middleware.
        return true;
    }

    public function rules(): array
    {
        return [
            'title' => ['required', 'string', 'max:255'],
            'slug' => [
                'required',
                'string',
                'max:255',
                'regex:/^[a-z0-9]+(?:-[a-z0-9]+)*$/',
                Rule::notIn(self::RESERVED_SLUGS),
                // On create route('page') is null, so nothing is ignored.
                Rule::unique('pages', 'slug')->ignore($this->route('page')),
            ],
            // Per-block-type rules for the content array.
            ...BlockDefinitions::contentRules($this->input('content')),
            'meta_title' => ['nullable', 'string', 'max:255'],
            'meta_description' => ['nullable', 'string', 'max:500'],
            'og_image_id' => ['nullable', 'integer', 'exists:media,id'],
        ];
    }

    /**
     * Readable field names for validation messages, so editors see
     * "The card title field is required." and not the raw path
     * "content.3.data.cards.0.title".
     */
    public function attributes(): array
    {
        $attributes = [];

        foreach (array_keys($this->rules()) as $key) {
            if (str_starts_with($key, 'content')) {
                $attributes[$key] = FieldLabels::for($key);
            }
        }

        return $attributes;
    }

    /**
     * Content is rebuilt from an allowlist of fields after validation, so
     * undeclared fields never reach the database and rich-text HTML is
     * always generated by the server.
     */
    public function validated($key = null, $default = null)
    {
        $validated = parent::validated();

        if (array_key_exists('content', $validated)) {
            $validated['content'] = BlockDefinitions::normalizeContent($validated['content']);
        }

        return $key === null ? $validated : data_get($validated, $key, $default);
    }
}
